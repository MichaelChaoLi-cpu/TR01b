from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/modis-land-cover/confirmed-inputs/modis_2003_mesh.parquet"
dst = ROOT / "data/processed/national/modis_land_cover/modis_land_cover_2003_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "mesh_code": "Mesh Code",
    "land_cover_year": "Land Cover Year",
    "urban_share": "Urban Land Cover Share",
    "forest_share": "Forest Land Cover Share",
    "cropland_share": "Cropland Land Cover Share",
    "cropland_mosaic_share": "Cropland Mosaic Land Cover Share",
    "water_share": "Water Land Cover Share",
    "other_share": "Other Land Cover Share",
    "source_coverage": "Land Cover Source Coverage",
    "valid_coverage": "Land Cover Coverage",
    "unclassified_share": "Land Cover Unclassified Share",
    "adjusted_share": "Land Cover Adjusted Share",
    "mesh_area": "Land Cover Mesh Area",
    "no_data_share": "Land Cover No Data Share",
    "no_valid_pixels": "Land Cover No Valid Pixels",
    "incomplete_coverage": "Land Cover Incomplete Coverage",
    "product": "Land Cover Product",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
