#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/regional/mesh_region_confirmed_input.parquet
Output: data/processed/national/mesh_region_national_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/regional/mesh_region_confirmed_input.parquet"
dst = ROOT / "data/processed/national/mesh_region_national_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "mesh_code": "Mesh Code",
    "region": "Region",
    "cross_region_mesh": "Cross Region Mesh",
    "region_land_area": "Region Land Area",
    "total_land_overlap": "Total Land Overlap",
    "region_land_share": "Region Land Share",
    "assignment_status": "Assignment Status",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
