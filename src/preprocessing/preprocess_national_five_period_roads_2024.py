#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/five-period-2024/confirmed-inputs/roads_2024_confirmed_input.parquet
Output: data/processed/national/five_period/roads_2024_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/five-period-2024/confirmed-inputs/roads_2024_confirmed_input.parquet"
dst = ROOT / "data/processed/national/five_period/roads_2024_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "mesh_code": "Mesh Code",
    "road_length_km": "Road Length",
    "road_length_density": "Road Length Density",
    "mesh_area_km2": "Mesh Area",
    "road_year": "Road Year",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
