#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/prefecture-population-zero-corrected/mesh_prefecture_reviewed_confirmed_input.parquet
Output: data/processed/national/population_zero_corrected/mesh_prefecture_national_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/prefecture-population-zero-corrected/mesh_prefecture_reviewed_confirmed_input.parquet"
dst = ROOT / "data/processed/national/population_zero_corrected/mesh_prefecture_national_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "mesh_code": "Mesh Code",
    "prefecture_code": "Prefecture Code",
    "prefecture": "Prefecture",
    "cross_prefecture_mesh": "Cross Prefecture Mesh",
    "prefecture_land_area": "Prefecture Land Area",
    "total_land_overlap": "Total Land Overlap",
    "prefecture_land_share": "Prefecture Land Share",
    "assignment_status": "Assignment Status",
    "no_land_overlap": "No Land Overlap",
    "prefecture_assignment_method": "Prefecture Assignment Method",
    "nearest_land_distance": "Nearest Land Distance",
    "region_from_prefecture": "Region From Prefecture",
    "prior_region": "Prior Region",
    "region_assignment_differs": "Region Assignment Differs",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
