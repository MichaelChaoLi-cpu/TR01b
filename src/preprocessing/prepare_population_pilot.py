#!/usr/bin/env python3
"""Prepare population inputs only after explicit variable/rule confirmation.

Original archives remain immutable. The per-dataset writers are generated by
the data-preprocessing skill from the resulting confirmed decision record.
"""
from pathlib import Path
import json
import sys

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'src/exp'))
from audit_population_pilot import read_source, FIELDS, sha

PILOT = ROOT / 'data/exp/data-preprocessing/pilot'
OUT = PILOT / 'population'
STAGING = PILOT / 'confirmed-inputs'


def variable(original, readable, final=False):
    return dict(original_name=original, readable_name=readable, full_name=readable,
                is_final_variable='yes' if final else 'no', preprocessing=[])


def main():
    contract_path = OUT / 'population_decisions.json'
    if not contract_path.exists():
        raise SystemExit('Population column names and rules await user confirmation; no inputs written.')
    contract = json.loads(contract_path.read_text())
    if not contract.get('confirmed', False):
        raise SystemExit('Population decision is not confirmed; no inputs written.')
    assert contract['keep_disclosed_total_regardless_of_detail_disclosure_status']
    assert contract['unlisted_or_nonnumeric_total'] == 'NaN'
    assert not contract['reaggregate_total']
    assert set(contract['population_years']) == set(FIELDS)
    STAGING.mkdir(parents=True, exist_ok=True)
    grid = pd.read_csv(PILOT / 'common_grid_trial.csv', dtype={'mesh_code': 'string'})
    assert len(grid) == 6400 and grid.mesh_code.is_unique
    datasets, quality = {}, []
    for year, field in FIELDS.items():
        source, archive, _ = read_source(year)
        assert sha(archive) == contract['raw_archive_sha256'][str(archive.relative_to(ROOT))]
        inputs = pd.DataFrame({'mesh_code': source.KEY_CODE,
                               'population': pd.to_numeric(source[field], errors='coerce').astype(float)})
        frame = grid[['mesh_code']].merge(inputs, on='mesh_code', how='left', validate='one_to_one')
        frame['population_year'] = year
        listed = frame.mesh_code.isin(source.KEY_CODE)
        assert frame.loc[~listed, 'population'].isna().all()
        indexed = source.set_index('KEY_CODE')
        specs = [variable('mesh_code', 'Mesh Code'), variable('population', 'Population', True),
                 variable('population_year', 'Population Year')]
        if year == 2020:
            frame['disclosure_status'] = pd.to_numeric(frame.mesh_code.map(indexed.HTKSYORI), errors='coerce')
            for original, internal, readable in [('HTKSAKI', 'disclosure_destination', 'Disclosure Destination'),
                                                  ('GASSAN', 'merged_mesh_codes', 'Merged Mesh Codes')]:
                frame[internal] = frame.mesh_code.map(indexed[original]).astype('string').replace('', pd.NA)
                specs.append(variable(internal, readable))
            specs.append(variable('disclosure_status', 'Disclosure Status'))
        literal = frame.mesh_code.map(indexed[field])
        flag = pd.DataFrame({'mesh_code': frame.mesh_code, 'population_year': year,
                             'source_row_present': listed, 'population_literal': literal,
                             'source_total_nonnumeric': listed & frame.population.isna(),
                             'total_population_published': listed & frame.population.notna(),
                             'detail_disclosure_status': frame['disclosure_status'] if year == 2020 else np.nan,
                             'disclosure_metadata_available': year == 2020,
                             'total_population_reaggregated': False})
        quality.append(flag)
        path = STAGING / f'population_{year}_confirmed_input.parquet'
        frame.to_parquet(path, index=False)
        datasets[str(path.relative_to(ROOT))] = dict(
            output=f'data/processed/pilot/population_{year}_preprocessed.parquet',
            script=f'src/preprocessing/preprocess_pilot_population_{year}.py', variables=specs,
            spatial_preparation='src/preprocessing/prepare_population_pilot.py',
            source_details=dict(raw_archive=str(archive.relative_to(ROOT)), total_field=field,
                                raw_archive_sha256=sha(archive), missing_rule=contract['unlisted_or_nonnumeric_total'],
                                preserve_disclosed_totals=True, reaggregate_total=False))
    pd.concat(quality, ignore_index=True).to_csv(OUT / 'population_quality_flags.csv', index=False)
    contract['datasets'] = datasets
    contract_path.write_text(json.dumps(contract, indent=2) + '\n')
    central = PILOT.parent / 'decisions.json'
    decisions = json.loads(central.read_text())
    decisions['datasets'].update(datasets)
    decisions['population_decisions'] = contract
    decisions['population_status'] = 'confirmed pilot total population; no final estimation sample selected'
    decisions['confirmed_decisions'] = list(dict.fromkeys(decisions['confirmed_decisions'] + [contract['decision_id']]))
    central.write_text(json.dumps(decisions, indent=2) + '\n')
    inventory_path = PILOT.parent / 'variable_list.csv'
    inventory = pd.read_csv(inventory_path, keep_default_na=False)
    for year, field in FIELDS.items():
        match = inventory.source_dataset.str.contains(f'population_{year}_{field[:-3]}_5030', regex=False)
        names = {'KEY_CODE': 'Mesh Code', field: 'Population'}
        if year == 2020:
            names.update(HTKSYORI='Disclosure Status', HTKSAKI='Disclosure Destination',
                         GASSAN='Merged Mesh Codes')
        for original, readable in names.items():
            selected = match & inventory.original_name.eq(original)
            assert selected.sum() == 1
            inventory.loc[selected, ['readable_name', 'full_name', 'is_final_variable']] = [
                readable, readable, 'yes' if readable == 'Population' else 'no']
    inventory.to_csv(inventory_path, index=False)
    print(json.dumps(dict(status='prepared', population_years=list(FIELDS), source_inputs=4,
                          rows_per_year=6400, population_variables_confirmed=True), indent=2))


if __name__ == '__main__':
    main()
