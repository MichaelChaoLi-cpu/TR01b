#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/ksj-eighteen-facilities/constructed-inputs/ksj_ports_mesh.parquet
Output: data/processed/national/ksj_eighteen_facilities/ports_mesh_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/ksj-eighteen-facilities/constructed-inputs/ksj_ports_mesh.parquet"
dst = ROOT / "data/processed/national/ksj_eighteen_facilities/ports_mesh_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "mesh_code": "Mesh Code",
    "observed_count": "Port Count",
    "archive_year": "Port Source Archive Year",
    "reference_year": "Port Source Reference Year",
    "coverage_complete": "Port Archive Coverage Complete",
    "declared_crs_used": "Port Declared CRS Used",
    "duplicate_present": "Port Exact Duplicate Present",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
