from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/municipality-mismatch-trial/municipal_code_crosswalk_confirmed_input.parquet"
dst = ROOT / "data/processed/national/municipality_mismatch_trial/municipal_code_crosswalk_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Municipality Code": "Municipality Code",
    "Prefecture Code": "Prefecture Code",
    "Boundary Municipality Name": "Boundary Municipality Name",
    "Boundary Ward Name": "Boundary Ward Name",
    "Government Code": "Government Code",
    "Government Name": "Government Name",
    "Linkage Rule": "Linkage Rule",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
