#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/static-facilities/confirmed-inputs/logistics_confirmed_input.parquet
Output: data/processed/national/static_facilities/logistics_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/static-facilities/confirmed-inputs/logistics_confirmed_input.parquet"
dst = ROOT / "data/processed/national/static_facilities/logistics_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Mesh Code": "Mesh Code",
    "Logistics Facility Count": "Logistics Facility Count",
    "Container Terminal Count": "Container Terminal Count",
    "Air Cargo Terminal Count": "Air Cargo Terminal Count",
    "Freight Railway Station Count": "Freight Railway Station Count",
    "Bonded Facility Count": "Bonded Facility Count",
    "Truck Terminal Count": "Truck Terminal Count",
    "Wholesale Market Count": "Wholesale Market Count",
    "Logistics Facility Source Year": "Logistics Facility Source Year",
    "Logistics Facility Archives Complete": "Logistics Facility Archives Complete",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
