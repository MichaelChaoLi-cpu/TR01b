#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/road-density-zero/confirmed-inputs/roads_2010_zero_input.parquet
Output: data/processed/national/road_density_zero/roads_2010_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/road-density-zero/confirmed-inputs/roads_2010_zero_input.parquet"
dst = ROOT / "data/processed/national/road_density_zero/roads_2010_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Mesh Code": "Mesh Code",
    "Road Length": "Road Length",
    "Road Length Density": "Road Length Density",
    "Mesh Area": "Mesh Area",
    "Road Year": "Road Year",
    "Road Density Originally Missing": "Road Density Originally Missing",
    "Road Density Source Status": "Road Density Source Status",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Variable-level preprocessing ---
# Road Length Density
df["Road Length Density"] = df["Road Length Density"].fillna(0)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
