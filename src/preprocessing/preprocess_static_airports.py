#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/static-facilities/confirmed-inputs/airports_confirmed_input.parquet
Output: data/processed/national/static_facilities/airports_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/static-facilities/confirmed-inputs/airports_confirmed_input.parquet"
dst = ROOT / "data/processed/national/static_facilities/airports_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Mesh Code": "Mesh Code",
    "Passenger Airport Count": "Passenger Airport Count",
    "Distance to Passenger Airport": "Distance to Passenger Airport",
    "Airport Source Year": "Airport Source Year",
    "Nearest Airport Terminal Code": "Nearest Airport Terminal Code",
    "Airport Archives Complete": "Airport Archives Complete",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
