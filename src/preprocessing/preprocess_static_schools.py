from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/static-facilities/confirmed-inputs/schools_confirmed_input.parquet"
dst = ROOT / "data/processed/national/static_facilities/schools_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Mesh Code": "Mesh Code",
    "School Facility Count": "School Facility Count",
    "Primary School Count": "Primary School Count",
    "Junior High School Count": "Junior High School Count",
    "Secondary School Count": "Secondary School Count",
    "High School Count": "High School Count",
    "Technical College Count": "Technical College Count",
    "Junior College Count": "Junior College Count",
    "University Count": "University Count",
    "Kindergarten Count": "Kindergarten Count",
    "Special Needs School Count": "Special Needs School Count",
    "Integrated Early Childhood Centre Count": "Integrated Early Childhood Centre Count",
    "Compulsory Education School Count": "Compulsory Education School Count",
    "Miscellaneous School Count": "Miscellaneous School Count",
    "Specialized Training College Count": "Specialized Training College Count",
    "School Facility Source Year": "School Facility Source Year",
    "School Facility Archives Complete": "School Facility Archives Complete",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
