#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/current-common-cohort/confirmed-inputs/baseline_panel_input.parquet
Output: data/processed/national/current_common_cohort/baseline_panel_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/current-common-cohort/confirmed-inputs/baseline_panel_input.parquet"
dst = ROOT / "data/processed/national/current_common_cohort/baseline_panel_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Mesh Code": "Mesh Code",
    "Road Year": "Road Year",
    "Population Year": "Population Year",
    "Nighttime Light Year": "Nighttime Light Year",
    "Nighttime Radiance": "Nighttime Radiance",
    "Road Length Density": "Road Length Density",
    "Population": "Population",
    "Region": "Region",
    "Prefecture Code": "Prefecture Code",
    "Prefecture": "Prefecture",
    "No Land Overlap": "No Land Overlap",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
