from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/municipality-mismatch-trial/mesh_municipality_reference_confirmed_input.parquet"
dst = ROOT / "data/processed/national/municipality_mismatch_trial/mesh_municipality_reference_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Mesh Code": "Mesh Code",
    "Prefecture Code": "Prefecture Code",
    "Municipality Name": "Municipality Name",
    "Cross Municipality Mesh": "Cross Municipality Mesh",
    "Assigned Municipal Land Area": "Assigned Municipal Land Area",
    "Total Municipal Land Overlap": "Total Municipal Land Overlap",
    "Municipal Land Share": "Municipal Land Share",
    "Municipality Assignment Status": "Municipality Assignment Status",
    "Government Code": "Government Code",
    "Government Name": "Government Name",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
